// Command generate-photo-policy writes the browser photo import extension policy.
package main

import (
	"bytes"
	"fmt"
	"log"
	"os"

	"go.kenn.io/docbank/internal/store"
)

func main() {
	var output bytes.Buffer
	output.WriteString("// Code generated by make generate-photo-policy. DO NOT EDIT.\n\n")
	output.WriteString("export const photoImportContentHashExtensions = new Set([\n")
	for _, extension := range store.PhotoSourceExtensions() {
		fmt.Fprintf(&output, "  %q,\n", extension)
	}
	output.WriteString("]);\n")
	if err := os.WriteFile("frontend/src/generated/photoSourceExtensions.ts", output.Bytes(), 0o644); err != nil { //nolint:gosec // G306: generated public source contains only supported photo extensions.
		log.Fatal(err)
	}
}
